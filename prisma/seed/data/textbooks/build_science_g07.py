import json, sys

def Q(text, correct, wrong, misconception=None):
    """One MCQ: a correct answer, three distractors."""
    choices = [{"text": correct, "correct": True}]
    for w in wrong:
        c = {"text": w, "correct": False}
        if misconception:
            c["misconception"] = misconception
        choices.append(c)
    return {"text": text, "choices": choices}

def C(slug, name, page, questions, threshold=0.75, difficulty=0.3,
      prerequisites=(), misconceptions=()):
    return {
        "slug": slug, "name": name, "page": page,
        "threshold": threshold, "difficulty": difficulty,
        "prerequisites": list(prerequisites),
        "misconceptions": list(misconceptions),
        "questions": questions,
    }

def MIS(slug, name, description, remediation):
    return {"slug": slug, "name": name, "description": description, "remediation": remediation}

