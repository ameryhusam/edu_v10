def main():
    book = {
        "$comment": [
            "Science G07 Part 1 — Yemeni national curriculum, authored from the book's",
            "own index and lesson summaries. Units and lessons keep the printed page",
            "numbers; concepts, questions, misconceptions and readings are authored",
            "content in the book's vocabulary.",
            "",
            "Invariants (asserted below, and again by the seed): slugs are unique",
            "book-wide; every question has exactly one correct choice; misconception",
            "slugs referenced from distractors exist on the same concept; explicit",
            "prerequisites resolve inside the book.",
        ],
        "subjectKey": "SCI",
        "gradeKey": "G07",
        "term": 1,
        "edition": "2026",
        "title": "العلوم — الصف السابع الأساسي — الجزء الأول",
        "issuer": "وزارة التربية والتعليم — اليمن",
        "totalPages": 171,
        "units": UNITS,
        "exams": [
            {
                "key": "EXAM-SCI-G07-U01-01",
                "title": "تقويم الوحدة الأولى: تركيب المادة",
                "description": "أسئلة تكيّفيّة على مفاهيم وحدة تركيب المادة.",
                "unitSlug": "STRUCTURE-OF-MATTER",
                "isAdaptive": True,
                "timeLimitMins": 10,
                "passingScore": 0.5,
            },
        ],
    }

    slugs = set()
    for u in book["units"]:
        assert u["slug"] not in slugs, f"duplicate unit slug {u['slug']}"
        slugs.add(u["slug"])
        for l in u["lessons"]:
            assert l["slug"] not in slugs, f"duplicate lesson slug {l['slug']}"
            slugs.add(l["slug"])
    concept_slugs = {}
    for u in book["units"]:
        for l in u["lessons"]:
            for c in l["concepts"]:
                assert c["slug"] not in concept_slugs, f"duplicate concept slug {c['slug']}"
                assert len(c["questions"]) == 2, f"{c['slug']}: questions must be 2"
                mis_slugs = {m["slug"] for m in c["misconceptions"]}
                for q in c["questions"]:
                    correct = [ch for ch in q["choices"] if ch["correct"]]
                    assert len(correct) == 1, f"{c['slug']}: exactly one correct choice"
                    assert len(q["choices"]) == 4, f"{c['slug']}: four choices"
                    for ch in q["choices"]:
                        if "misconception" in ch:
                            assert ch["misconception"] in mis_slugs, \
                                f"{c['slug']}: distractor tags unknown misconception"
                for p in c["prerequisites"]:
                    assert p in concept_slugs or p in {x["slug"] for x in l["concepts"]}, \
                        f"{c['slug']}: prerequisite {p} not authored before it"
                assert c["slug"] not in c["prerequisites"]
                concept_slugs[c["slug"]] = True

    n_concepts = sum(len(l["concepts"]) for u in book["units"] for l in u["lessons"])
    n_questions = sum(len(c["questions"]) for u in book["units"] for l in u["lessons"] for c in l["concepts"])
    n_mis = sum(len(c["misconceptions"]) for u in book["units"] for l in u["lessons"] for c in l["concepts"])
    out = "science-g07.json"
    with open(out, "w", encoding="utf-8") as f:
        json.dump(book, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"{out}: {len(book['units'])} units, "
          f"{sum(len(u['lessons']) for u in book['units'])} lessons, "
          f"{n_concepts} concepts, {n_questions} questions, {n_mis} misconceptions")

if __name__ == "__main__":
    main()
