/**
 * Generate the single baseline migration from prisma/schema.prisma.
 *
 * Uses the WASM schema engine directly so it works with no database and no
 * native engine download.
 *
 *   node scripts/generate-baseline.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SCHEMA = path.join(ROOT, 'prisma', 'schema.prisma');
const OUT_DIR = path.join(ROOT, 'prisma', 'migrations', '00000000000000_baseline');

// The WASM build expects a panic registry on globalThis; without it any
// engine panic surfaces as an unrelated TypeError and hides the real cause.
let panicMessage = null;
globalThis.PRISMA_WASM_PANIC_REGISTRY = {
  set_message(msg) {
    panicMessage = msg;
  },
};

const enginePath = path.join(ROOT, 'node_modules', '@prisma', 'schema-engine-wasm', 'schema_engine.js');
const { SchemaEngine } = await import(enginePath);

const content = fs.readFileSync(SCHEMA, 'utf8');
const files = [{ content, path: 'prisma/schema.prisma' }];
// The engine needs a real adapter to know which SQL dialect to emit.
const { PrismaPg } = await import('@prisma/adapter-pg');
const { bindSqlAdapterFactory } = await import('@prisma/driver-adapter-utils');
const url =
  process.env.DATABASE_URL ?? 'postgresql://postgres:postgres@127.0.0.1:5432/postgres';
const adapter = bindSqlAdapterFactory(new PrismaPg({ connectionString: url }));

const engine = await SchemaEngine.new(
  { datamodels: [[content, 'prisma/schema.prisma']] },
  () => {},
  adapter,
);

let result;
try {
  result = await engine.diff({
    from: { tag: 'empty' },
    to: { tag: 'schemaDatamodel', files },
    script: true,
    exitCode: null,
    shadowDatabaseUrl: null,
    filters: { externalTables: [], externalEnums: [] },
  });
} catch (err) {
  console.error('engine.diff failed:', panicMessage ?? err?.message ?? err);
  process.exit(1);
}

const sql = typeof result === 'string' ? result : (result?.stdout ?? result?.script ?? '');
if (!sql || !sql.trim()) {
  console.error('No SQL produced. Engine returned:', JSON.stringify(result).slice(0, 500));
  process.exit(1);
}

/**
 * Constraints Prisma's schema language cannot express.
 *
 * Appended by the GENERATOR rather than hand-edited into the output, because
 * this file is overwritten wholesale on every regeneration — a hand-added
 * index would silently disappear the next time someone touched the schema, and
 * the constraint would be gone long before anyone noticed.
 */
const PARTIAL_INDEXES = `
-- ─────────────────────────────────────────────────────────────────────────────
-- Partial indexes: not expressible in the Prisma schema language.
-- ─────────────────────────────────────────────────────────────────────────────

-- One OPEN remediation episode per (learner, concept, trigger, misconception).
--
-- Deliberately NOT a plain @@unique on those columns: that would forbid the
-- re-opening the design requires, because a RESOLVED episode would block a
-- genuine new gap from ever being recorded. Scoping uniqueness to OPEN rows
-- gives idempotent detection at the database level rather than trusting
-- application logic alone — the lesson from the obligation work, where an
-- application de-dupe needed a real constraint behind it.
--
-- COALESCE because NULL never equals NULL in a unique index, so without it two
-- open MASTERY_GAP episodes (misconceptionId IS NULL) would both be accepted.
CREATE UNIQUE INDEX "remediation_one_open_per_gap"
  ON "remediation_episodes" (
    "learnerId",
    "conceptId",
    "trigger",
    COALESCE("misconceptionId", '00000000-0000-0000-0000-000000000000'::uuid)
  )
  WHERE "status" = 'OPEN';
`;

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(path.join(OUT_DIR, 'migration.sql'), sql + PARTIAL_INDEXES);
fs.writeFileSync(
  path.join(ROOT, 'prisma', 'migrations', 'migration_lock.toml'),
  '# Do not edit. Generated by Prisma.\nprovider = "postgresql"\n',
);
console.log(
  `baseline migration written: ${(sql + PARTIAL_INDEXES).split('\n').length} lines ` +
    `(including ${PARTIAL_INDEXES.trim().split('CREATE UNIQUE INDEX').length - 1} partial index/es)`,
);
