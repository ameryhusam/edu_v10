export const MESSAGES: Record<Locale, Record<MessageKey, string>> = { ar, en };

/**
 * Look up a message and substitute `{placeholders}`.
 *
 * Falls back to the key itself rather than to an empty string: a visible
 * `nav.home` in the UI is an obvious bug report, whereas a blank space is a
 * mystery nobody files.
 */
export function translate(
  locale: Locale,
  key: MessageKey,
  values?: Record<string, string | number>,
): string {
  const template = MESSAGES[locale][key] ?? key;
  if (!values) return template;

  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match,
  );
}
